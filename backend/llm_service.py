import os
import requests

def generate_response(user_query: str, retrieved_context: str, language: str) -> str:
    """Generates a response using the Gemini API or a mock if no key is set."""
    api_key = os.environ.get("GEMINI_API_KEY")
    
    if api_key:
        try:
            from google import genai
            client = genai.Client(api_key=api_key)
            prompt = f"You are a helpful customer service agent. Use the following context to answer the user's question.\nContext:\n{retrieved_context}\n\nUser Question: {user_query}\n\nAnswer concisely. CRITICAL: You MUST respond in the language corresponding to this language code: '{language}'."
            response = client.models.generate_content(
                model='gemini-2.5-flash',
                contents=prompt
            )
            return response.text
        except Exception as e:
            print(f"Gemini API Error: {e}")
            return _mock_generate(retrieved_context, language)
    else:
        return _mock_generate(retrieved_context, language)

def generate_response_groq(user_query: str, retrieved_context: str, language: str) -> str:
    """Generates a response using the Groq API for ultra-fast throughput."""
    api_key = os.environ.get("GROQ_API_KEY")
    url = "https://api.groq.com/openai/v1/chat/completions"
    
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    
    prompt = f"You are a helpful customer service agent. Use the following context to answer the user's question.\nContext:\n{retrieved_context}\n\nUser Question: {user_query}\n\nAnswer concisely. CRITICAL: You MUST respond in the language corresponding to this language code: '{language}'."
    
    data = {
        "model": "llama-3.1-8b-instant",
        "messages": [
            {"role": "system", "content": "You are a fast, helpful AI assistant."},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.5,
        "max_tokens": 150
    }
    
    try:
        response = requests.post(url, headers=headers, json=data)
        response.raise_for_status()
        return response.json()["choices"][0]["message"]["content"].strip()
    except Exception as e:
        print(f"Groq API Error: {e}")
        return _mock_generate(retrieved_context, language)

def _mock_generate(retrieved_context: str, language: str) -> str:
    # A simple mock that just returns the top retrieved context wrapped in a conversational tone.
    # Note: For real language translation, please provide a GEMINI_API_KEY.
    base_response = retrieved_context.split('\n')[0]
    if language == 'hi':
        return "हमारे रिकॉर्ड के अनुसार: (mock translation) " + base_response
    return "Based on our records: " + base_response

import httpx
import json

async def generate_response_groq_stream(user_query: str, retrieved_context: str, language: str):
    """Yields text tokens as they are generated by the Groq API for ultra-fast throughput."""
    api_key = os.environ.get("GROQ_API_KEY")
    url = "https://api.groq.com/openai/v1/chat/completions"
    
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    
    prompt = f"You are a helpful customer service agent. Use the following context to answer the user's question.\nContext:\n{retrieved_context}\n\nUser Question: {user_query}\n\nAnswer concisely. CRITICAL: You MUST respond in the language corresponding to this language code: '{language}'."
    
    data = {
        "model": "llama-3.1-8b-instant",
        "messages": [
            {"role": "system", "content": "You are a fast, helpful AI assistant."},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.5,
        "max_tokens": 150,
        "stream": True
    }
    
    try:
        async with httpx.AsyncClient() as client:
            async with client.stream("POST", url, headers=headers, json=data) as response:
                response.raise_for_status()
                async for line in response.aiter_lines():
                    if line.startswith("data: "):
                        line = line[6:]
                        if line == "[DONE]":
                            break
                        try:
                            chunk = json.loads(line)
                            content = chunk["choices"][0]["delta"].get("content", "")
                            if content:
                                yield content
                        except json.JSONDecodeError:
                            pass
    except Exception as e:
        print(f"Groq API Stream Error: {e}")
        # fallback to non-streaming mock, but yield it in one chunk
        fallback = _mock_generate(retrieved_context, language)
        yield fallback
